using System.Globalization;
using Npgsql;
using NpgsqlTypes;

class ConfigData
{
    required public string Host { get; set; }
    required public int Port { get; set; }
    required public string Username { get; set; }
    required public string Password { get; set; }
    required public string Database { get; set; }
}

class Student
{
    public int Id { get; set; }
    required public string Name { get; set; }
    public int? Age { get; set; }
    public decimal? GPA { get; set; }
}

class Database
{
    private readonly string _connectionString;

    public Database(ConfigData config)
    {
        _connectionString =
            $"Host={config.Host};Port={config.Port};Username={config.Username};" +
            $"Password={config.Password};Database={config.Database}";
    }

    // Prints the SQL 
    private static void Log(string sql) => Console.WriteLine($"  [SQL] {sql}");

    private static NpgsqlParameter IntParam(string name, int? value) =>
        new(name, NpgsqlDbType.Integer) { Value = (object?)value ?? DBNull.Value };

    private static NpgsqlParameter GpaParam(string name, decimal? value) =>
        new(name, NpgsqlDbType.Numeric) { Value = (object?)value ?? DBNull.Value };

    // ---------- CREATE TABLE ----------
    public void CreateTable()
    {
        const string sql = @"CREATE TABLE IF NOT EXISTS Student (
            Id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            Name VARCHAR(100) NOT NULL,
            Age INTEGER,
            GPA DECIMAL(3,2)
        )";

        try
        {
            using var connection = new NpgsqlConnection(_connectionString);
            connection.Open();
            using var cmd = new NpgsqlCommand(sql, connection);
            Log(sql);
            cmd.ExecuteNonQuery();
            Console.WriteLine("Student table is ready.");
        }
        catch (Exception e)
        {
            Console.WriteLine("Error creating table: " + e.Message);
        }
    }

    // ---------- CREATE ----------
    public void AddStudent(Student s)
    {
        const string sql = "INSERT INTO Student (Name, Age, GPA) VALUES (@name, @age, @gpa) RETURNING Id";

        try
        {
            using var connection = new NpgsqlConnection(_connectionString);
            connection.Open();
            using var cmd = new NpgsqlCommand(sql, connection);
            cmd.Parameters.AddWithValue("name", s.Name);
            cmd.Parameters.Add(IntParam("age", s.Age));
            cmd.Parameters.Add(GpaParam("gpa", s.GPA));

            Log(sql);
            object? newId = cmd.ExecuteScalar();
            Console.WriteLine($"Student added with Id = {newId}.");
        }
        catch (Exception e)
        {
            Console.WriteLine("Error adding student: " + e.Message);
        }
    }

    // ---------- READ ----------
    public void ViewStudents()
    {
        const string sql = "SELECT Id, Name, Age, GPA FROM Student ORDER BY Id";

        try
        {
            using var connection = new NpgsqlConnection(_connectionString);
            connection.Open();
            using var cmd = new NpgsqlCommand(sql, connection);
            Log(sql);
            using var reader = cmd.ExecuteReader();

            Console.WriteLine();
            Console.WriteLine($"{"Id",-5}{"Name",-30}{"Age",-6}{"GPA",-6}");
            Console.WriteLine(new string('-', 47));

            int count = 0;
            while (reader.Read())
            {
                int id = reader.GetInt32(0);
                string name = reader.GetString(1);
                string age = reader.IsDBNull(2) ? "-" : reader.GetInt32(2).ToString();
                string gpa = reader.IsDBNull(3) ? "-" : reader.GetDecimal(3).ToString("0.00", CultureInfo.InvariantCulture);
                Console.WriteLine($"{id,-5}{name,-30}{age,-6}{gpa,-6}");
                count++;
            }

            if (count == 0) Console.WriteLine("No students found.");
        }
        catch (Exception e)
        {
            Console.WriteLine("Error reading students: " + e.Message);
        }
    }

    // ---------- UPDATE ----------
    public void UpdateStudent(Student s)
    {
        const string sql = "UPDATE Student SET Name = @name, Age = @age, GPA = @gpa WHERE Id = @id";

        try
        {
            using var connection = new NpgsqlConnection(_connectionString);
            connection.Open();
            using var cmd = new NpgsqlCommand(sql, connection);
            cmd.Parameters.AddWithValue("name", s.Name);
            cmd.Parameters.Add(IntParam("age", s.Age));
            cmd.Parameters.Add(GpaParam("gpa", s.GPA));
            cmd.Parameters.AddWithValue("id", s.Id);

            Log(sql);
            int rows = cmd.ExecuteNonQuery();
            Console.WriteLine(rows == 0
                ? $"No student with Id = {s.Id}."
                : $"Student {s.Id} updated.");
        }
        catch (Exception e)
        {
            Console.WriteLine("Error updating student: " + e.Message);
        }
    }

    // ---------- DELETE ----------
    public void DeleteStudent(int id)
    {
        const string sql = "DELETE FROM Student WHERE Id = @id";

        try
        {
            using var connection = new NpgsqlConnection(_connectionString);
            connection.Open();
            using var cmd = new NpgsqlCommand(sql, connection);
            cmd.Parameters.AddWithValue("id", id);

            Log(sql);
            int rows = cmd.ExecuteNonQuery();
            Console.WriteLine(rows == 0
                ? $"No student with Id = {id}."
                : $"Student {id} deleted.");
        }
        catch (Exception e)
        {
            Console.WriteLine("Error deleting student: " + e.Message);
        }
    }
}

// ---------------- Runner code ----------------

class Program
{
    static void Main(string[] args)
    {
        ConfigData config = new()
        {
            Host = "localhost",
            Port = 5432,
            Username = "mohh",
            Password = "abosaree",
            Database = "students"
        };

        Database database = new(config);
        database.CreateTable();

        while (true)
        {
            Console.WriteLine();
            Console.WriteLine("===== Student Management System =====");
            Console.WriteLine("1. Add Student");
            Console.WriteLine("2. View Students");
            Console.WriteLine("3. Update Student");
            Console.WriteLine("4. Delete Student");
            Console.WriteLine("0. Exit");
            Console.Write("Choose an option: ");

            switch (Console.ReadLine()?.Trim())
            {
                case "1":
                    database.AddStudent(new Student
                    {
                        Name = ReadName(),
                        Age = ReadOptionalInt("Age (blank for none): "),
                        GPA = ReadOptionalGpa("GPA 0.00-4.00 (blank for none): ")
                    });
                    break;

                case "2":
                    database.ViewStudents();
                    break;

                case "3":
                    int updateId = ReadInt("Id of student to update: ");
                    database.UpdateStudent(new Student
                    {
                        Id = updateId,
                        Name = ReadName(),
                        Age = ReadOptionalInt("New age (blank for none): "),
                        GPA = ReadOptionalGpa("New GPA 0.00-4.00 (blank for none): ")
                    });
                    break;

                case "4":
                    database.DeleteStudent(ReadInt("Id of student to delete: "));
                    break;

                case "0":
                    Console.WriteLine("Goodbye!");
                    return;

                default:
                    Console.WriteLine("Invalid option, try again.");
                    break;
            }
        }
    }

    // ---------- input helpers ----------

    static string ReadName()
    {
        while (true)
        {
            Console.Write("Name: ");
            string? name = Console.ReadLine()?.Trim();
            if (!string.IsNullOrEmpty(name) && name.Length <= 100) return name;
            Console.WriteLine("Name is required (max 100 characters).");
        }
    }

    static int ReadInt(string prompt)
    {
        while (true)
        {
            Console.Write(prompt);
            if (int.TryParse(Console.ReadLine(), out int value)) return value;
            Console.WriteLine("Please enter a valid whole number.");
        }
    }

    static int? ReadOptionalInt(string prompt)
    {
        while (true)
        {
            Console.Write(prompt);
            string? input = Console.ReadLine()?.Trim();
            if (string.IsNullOrEmpty(input)) return null;
            if (int.TryParse(input, out int value) && value >= 0) return value;
            Console.WriteLine("Please enter a valid non-negative whole number.");
        }
    }

    static decimal? ReadOptionalGpa(string prompt)
    {
        while (true)
        {
            Console.Write(prompt);
            string? input = Console.ReadLine()?.Trim();
            if (string.IsNullOrEmpty(input)) return null;
            if (decimal.TryParse(input, NumberStyles.Number, CultureInfo.InvariantCulture, out decimal value)
                && value >= 0m && value <= 4.00m)
                return Math.Round(value, 2);
            Console.WriteLine("Please enter a GPA between 0.00 and 4.00 (use '.' as the decimal separator).");
        }
    }
}